mark() { if [ -e "$1" ]; then printf '  [x] %s\n' "$1"; else printf '  [ ] %s\n' "$1"; fi; }

do_status() {
  [ -f "$OSSEC_CONF" ] || die "$OSSEC_CONF not found - is this the Wazuh manager?"
  say "wazuh-s1-usb-install.sh $VERSION - status"
  say ""
  say "Files:"
  mark "$RULE_USB"; mark "$RULE_GEN"; mark "$LIST"; mark "$TOOL"
  mark "$RULE_S1"; mark "$RULE_DC"; mark "$POLLER"; mark "$CRED"; mark "$LOGROTATE"
  say ""
  say "ossec.conf:"
  if grep -q 'BEGIN wazuh-s1-usb' "$OSSEC_CONF"; then say "  [x] SentinelOne collector block"; else say "  [ ] SentinelOne collector block"; fi
  if grep -q "<list>$LIST_REL</list>" "$OSSEC_CONF"; then say "  [x] Approved USB list registered"; else say "  [ ] Approved USB list registered"; fi
  say ""
  say "Agent groups with the pushed Windows settings:"
  local f any=0
  for f in "$OSSEC"/etc/shared/*/agent.conf; do
    [ -e "$f" ] || continue
    if grep -q 'BEGIN wazuh-s1-usb' "$f"; then say "  [x] $(basename "$(dirname "$f")")"; any=1; fi
  done
  [ "$any" -eq 1 ] || say "  (none)"
  say ""
  say "Approved USB devices:"
  if [ -f "$LIST" ]; then
    if grep -v "^PLACEHOLDER-" "$LIST" | grep -q .; then grep -v "^PLACEHOLDER-" "$LIST" | sed 's/^\([^:]*\):\(.*\)$/  \1  \2/'
    else say "  (none yet)"; fi
  else say "  (list not installed)"; fi
  if [ -e "$POLLER" ]; then
    say ""
    say "SentinelOne collection:"
    if [ -f "$STATE" ]; then say "  last positions: $(tr -d '\n' < "$STATE")"; else say "  the collector has not completed a run yet"; fi
    if [ -s "$S1LOG" ]; then
      say "  events in the current log file, by type:"
      grep -o '"s1_type":"[a-z_]*"' "$S1LOG" | sort | uniq -c | sed 's/^/    /'
      if grep -q '"s1_type":"collector_error"' "$S1LOG"; then
        say "  most recent collector error:"
        grep '"s1_type":"collector_error"' "$S1LOG" | tail -n 1 | cut -c1-300 | sed 's/^/    /'
      fi
    else
      say "  no events in $S1LOG"
    fi
  fi
  local alerts="$OSSEC/logs/alerts/alerts.json"
  if [ -r "$alerts" ]; then
    say ""
    say "Alerts today from these rules (rule ID, count):"
    grep -oE '"id":"(1006[0-2][0-9]|1015[01][0-9])"' "$alerts" 2>/dev/null \
      | grep -oE '[0-9]+' | sort | uniq -c | awk '{printf "  %s  %s\n", $2, $1}' || true
  fi
}

# ----------------------------------------------------------------------------
# uninstall
# ----------------------------------------------------------------------------
do_uninstall() {
  need_root
  [ -f "$OSSEC_CONF" ] || die "$OSSEC_CONF not found - is this the Wazuh manager?"
  is_installed || die "nothing from this script is installed"
  if [ "$ASSUME_YES" -eq 0 ] && [ -t 0 ]; then
    local a
    read -r -p "Remove the SentinelOne collector, all rules from this script, the Approved USB list and usb-approve? [y/N] " a
    case "$a" in y|Y|yes|YES) ;; *) die "cancelled" ;; esac
  fi
  if ! BASE_OUT=$(run_t "$OSSEC/bin/wazuh-analysisd" -t); then BASE_OUT=""; fi
  BASE_WARN=$(warnings_of "$BASE_OUT")
  WORK=$(mktemp -d)
  write_payload_confedit > "$WORK/confedit.py"
  start_backup
  say "Backup: $BK"
  CHANGED=1

  local f
  track "$OSSEC_CONF"
  for f in "$CRED" "$POLLER" "$STATE" "$RULE_S1" "$RULE_USB" "$RULE_DC" "$RULE_GEN" "$LIST" "$LIST.cdb" "$TOOL" "$LOGROTATE"; do track "$f"; done
  confedit ossec-block-del "$OSSEC_CONF" || rollback "could not edit ossec.conf"
  confedit list-del "$OSSEC_CONF" "$LIST_REL" || rollback "could not edit ossec.conf"
  for f in "$OSSEC"/etc/shared/*/agent.conf; do
    [ -e "$f" ] || continue
    if grep -q 'BEGIN wazuh-s1-usb' "$f"; then
      track "$f"
      confedit agent-del "$f" || rollback "could not edit $f"
    fi
  done
  rm -f "$CRED" "$POLLER" "$STATE" "$RULE_S1" "$RULE_USB" "$RULE_DC" "$RULE_GEN" "$LIST" "$LIST.cdb" "$TOOL" "$LOGROTATE"

  NO_AGENT_CONF=0; VAC_BASE_OK=0
  validate || rollback "the configuration did not validate after removal"
  if [ "$NO_RESTART" -eq 1 ]; then
    say "Not restarting (--no-restart). Run:  systemctl restart wazuh-manager"
  else
    restart_manager || rollback "wazuh-manager did not restart"
    RESTARTED=1
    wait_manager || rollback "wazuh-manager is not running after the restart"
    say "wazuh-manager restarted."
  fi
  say "Removed. Everything that was removed is saved in $BK"
  say "Collected SentinelOne events were left in $LOGDIR."
}

# ----------------------------------------------------------------------------
# main
# ----------------------------------------------------------------------------
[ $# -ge 1 ] || { usage; exit 1; }
ACTION="$1"; shift
while [ $# -gt 0 ]; do
  case "$1" in
    --s1-url)         S1_URL="${2:-}"; shift 2 ;;
    --s1-site-id)     S1_SITE="${2:-}"; shift 2 ;;
    --s1-token-file)  S1_TOKEN_FILE="${2:-}"; shift 2 ;;
    --usb-only)       USB_ONLY=1; shift ;;
    --agent-group)    AGENT_GROUPS+=("${2:-}"); shift 2 ;;
    --no-agent-conf)  NO_AGENT_CONF=1; shift ;;
    --no-restart)     NO_RESTART=1; shift ;;
    -y|--yes)         ASSUME_YES=1; shift ;;
    -h|--help)        usage; exit 0 ;;
    *) die "unknown option: $1 (try: $0 help)" ;;
  esac
done

case "$ACTION" in
  install)   do_install ;;
  status)    do_status ;;
  selftest)  need_root; selftest ;;
  uninstall) do_uninstall ;;
  version)   say "$VERSION" ;;
  help|-h|--help) usage ;;
  *) usage; exit 1 ;;
esac
