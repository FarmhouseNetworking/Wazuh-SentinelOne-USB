need_root() { [ "$(id -u)" -eq 0 ] || die "run this as root (sudo)"; }

preflight() {
  need_root
  [ -f "$OSSEC_CONF" ] || die "$OSSEC_CONF not found - is this the Wazuh manager?"
  local info ver major minor
  info=$("$OSSEC/bin/wazuh-control" info 2>/dev/null || true)
  printf '%s' "$info" | grep -q 'WAZUH_TYPE="server"' || die "this is not a Wazuh manager (wazuh-control info does not report type server)"
  ver=$(printf '%s' "$info" | sed -n 's/^WAZUH_VERSION="v\{0,1\}\([0-9.]*\)".*/\1/p')
  major=${ver%%.*}; minor=${ver#*.}; minor=${minor%%.*}
  if [ -z "$ver" ] || [ "${major:-0}" -lt 4 ] || { [ "$major" -eq 4 ] && [ "${minor:-0}" -lt 3 ]; }; then
    die "Wazuh 4.3 or newer is required (found: ${ver:-unknown})"
  fi
  say "Wazuh manager $ver"
  [ -x "$PY" ] || die "Wazuh's bundled Python not found at $PY"
  if [ "$USB_ONLY" -eq 0 ]; then
    "$PY" -c 'import requests' 2>/dev/null || die "the 'requests' module is missing from $PY"
    command -v curl >/dev/null 2>&1 || die "curl is required"
  fi

  # Rule IDs must be free everywhere except in our own files.
  local pat='id="(1006[0-2][0-9]|1015[01][0-9])"' hits
  [ "$USB_ONLY" -eq 1 ] && pat='id="1015[01][0-9]"'
  hits=$(grep -rlE "$pat" "$OSSEC/etc/rules" 2>/dev/null \
         | grep -vxF -e "$RULE_S1" -e "$RULE_USB" -e "$RULE_DC" -e "$RULE_GEN" || true)
  if [ -n "$hits" ]; then
    printf '%s\n' "$hits" >&2
    die "rule IDs this script uses (100600-100629, 101500-101519) already appear in the file(s) above. See docs/TROUBLESHOOTING.md, 'Rule IDs already in use'."
  fi

  # An earlier hand-made install of the poller would run twice.
  if sed '/BEGIN wazuh-s1-usb/,/END wazuh-s1-usb/d' "$OSSEC_CONF" | grep -q '<tag>sentinelone-pull</tag>'; then
    die "ossec.conf already has a 'sentinelone-pull' command block that this script did not create. Remove it first (see docs/TROUBLESHOOTING.md, 'Moving from a hand-made install')."
  fi

  if ! BASE_OUT=$(run_t "$OSSEC/bin/wazuh-analysisd" -t) || printf '%s' "$BASE_OUT" | grep -qE 'ERROR|CRITICAL'; then
    printf '%s\n' "$BASE_OUT" | grep -E 'ERROR|CRITICAL' >&2 || true
    die "wazuh-analysisd -t already reports errors on this server. Fix those first."
  fi
  BASE_WARN=$(warnings_of "$BASE_OUT")
  # Only hold verify-agent-conf against this install if it passed beforehand.
  VAC_BASE_OK=0
  if [ -x "$OSSEC/bin/verify-agent-conf" ] && "$OSSEC/bin/verify-agent-conf" >/dev/null 2>&1; then VAC_BASE_OK=1; fi
}

clean() { printf '%s' "$1" | tr -d '[:space:]'; }

get_credentials() {
  KEEP_CRED=0
  if [ -z "$S1_URL" ] && [ -z "$S1_TOKEN" ] && [ -z "$S1_TOKEN_FILE" ] && [ -f "$CRED" ]; then
    KEEP_CRED=1
    say "Keeping the saved SentinelOne credentials in $CRED"
    return 0
  fi
  if [ -n "$S1_TOKEN_FILE" ]; then
    [ -r "$S1_TOKEN_FILE" ] || die "cannot read token file $S1_TOKEN_FILE"
    S1_TOKEN=$(head -n 1 "$S1_TOKEN_FILE")
  fi
  if [ -t 0 ]; then
    [ -n "$S1_URL" ] || read -r -p "SentinelOne console URL (e.g. https://usea1-xxxx.sentinelone.net): " S1_URL
    if [ -z "$S1_TOKEN" ]; then read -r -s -p "SentinelOne API token (input is hidden): " S1_TOKEN; echo; fi
    [ -n "$S1_SITE" ] || read -r -p "Site ID to collect from (blank = everything the token can see): " S1_SITE
  fi
  S1_URL=$(clean "$S1_URL"); S1_URL=${S1_URL%/}
  S1_TOKEN=$(clean "$S1_TOKEN")
  S1_SITE=$(clean "$S1_SITE")
  [ -n "$S1_URL" ]   || die "no SentinelOne console URL given (--s1-url)"
  [ -n "$S1_TOKEN" ] || die "no SentinelOne API token given (--s1-token-file, S1_API_TOKEN, or type it when asked)"
  case "$S1_URL" in https://*) ;; *) die "the console URL must start with https://" ;; esac
  case "$S1_SITE" in *[!0-9,]*) die "the site ID must be digits (several IDs separated by commas)" ;; esac
  say "Token length: ${#S1_TOKEN} characters"
}

api_code() {         # api_code <path?query>  -> prints the HTTP status code
  printf 'header = "Authorization: ApiToken %s"\n' "$S1_TOKEN" \
    | curl -sS -K - -o "$WORK/api.out" -w '%{http_code}' --max-time 30 "$S1_URL$1" 2>"$WORK/api.err" || true
}

api_test() {
  [ "$KEEP_CRED" -eq 1 ] && return 0
  local q="limit=1" code ep
  [ -n "$S1_SITE" ] && q="$q&siteIds=$S1_SITE"
  for ep in threats activities; do
    code=$(api_code "/web/api/v2.1/$ep?$q")
    case "$code" in
      200) say "SentinelOne API: $ep OK" ;;
      401) die "SentinelOne rejected the token (HTTP 401). It is wrong, cut short, expired, or from a different console." ;;
      403) die "the token is valid but not allowed to read $ep for that site (HTTP 403). Check the service user's role and scope." ;;
      000|"") die "could not reach $S1_URL ($(head -c 200 "$WORK/api.err" 2>/dev/null)). Check the URL and outbound HTTPS from this server." ;;
      *)   die "SentinelOne API returned HTTP $code for $ep: $(head -c 300 "$WORK/api.out" 2>/dev/null)" ;;
    esac
  done
}

# ----------------------------------------------------------------------------
# Validation and self-test
# ----------------------------------------------------------------------------
validate() {
  local out new
  if ! out=$(run_t "$OSSEC/bin/wazuh-analysisd" -t) || printf '%s' "$out" | grep -qE 'ERROR|CRITICAL'; then
    printf '%s\n' "$out" | grep -E 'ERROR|CRITICAL' >&2 || true
    return 1
  fi
  new=$(comm -13 <(printf '%s\n' "$BASE_WARN") <(warnings_of "$out") | sed '/^$/d')
  if [ -n "$new" ]; then
    printf 'New warnings from wazuh-analysisd -t:\n%s\n' "$new" >&2
    return 1
  fi
  if [ -x "$OSSEC/bin/wazuh-logcollector" ]; then
    if ! out=$(run_t "$OSSEC/bin/wazuh-logcollector" -t); then printf '%s\n' "$out" >&2; return 1; fi
  fi
  if [ "$NO_AGENT_CONF" -eq 0 ] && [ "${VAC_BASE_OK:-0}" -eq 1 ]; then
    if ! out=$(run_t "$OSSEC/bin/verify-agent-conf"); then printf '%s\n' "$out" >&2; return 1; fi
  fi
  return 0
}

logtest_id() {       # logtest_id <one log line> -> prints the rule ID that fired (or nothing)
  printf '%s\n' "$1" | timeout 30 "$OSSEC/bin/wazuh-logtest" 2>&1 \
    | grep -E "^[[:space:]]+id: '" | head -n 1 | grep -oE '[0-9]+' || true
}

selftest() {
  if ! s1_installed; then
    say "Self-test: skipped. Only the Windows USB rules are installed, and Windows events"
    say "cannot be replayed through wazuh-logtest. Test with a real device (docs/SETUP.md)."
    return 0
  fi
  local exp json got fails=0 total=0 attempt
  for attempt in 1 2 3; do
    fails=0; total=0
    while IFS=$'\t' read -r exp json; do
      [ -n "$exp" ] || continue
      case "$exp" in \#*) continue ;; esac
      total=$((total + 1))
      got=$(logtest_id "$json")
      if [ "$got" != "$exp" ]; then
        fails=$((fails + 1))
        [ "$attempt" -eq 3 ] && printf '  FAIL: expected rule %s, got %s\n' "$exp" "${got:-nothing}" >&2
      fi
    done < <(write_payload_samples)
    [ "$fails" -eq 0 ] && break
    nap 10
  done
  if [ "$fails" -eq 0 ]; then say "Self-test: $total of $total sample events hit the expected rule."; return 0; fi
  printf 'Self-test: %s of %s sample events did NOT hit the expected rule.\n' "$fails" "$total" >&2
  return 1
}

