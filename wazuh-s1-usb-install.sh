cat <<'__S1USB_EOF_TOOL__'
#!/usr/bin/env python3
"""usb-approve - maintain the Approved USB list on a Wazuh manager.

  usb-approve SERIAL LABEL     add a device, rebuild rules, validate, restart
  usb-approve --remove SERIAL  remove a device, rebuild, validate, restart
  usb-approve --rebuild        rebuild rules from the list, validate, restart
  usb-approve --generate       rebuild the rules file only (no validate, no restart)
  usb-approve --list           show the list (no changes)

The list (etc/lists/approved_usb_serials, one "serial:label" per line) is the
single source. This tool regenerates
etc/rules/9999_0012_usb_approved_generated.xml (rules 101516 and 101517) from it.

The list only LABELS events in Wazuh. Whatever blocks USB storage on the
endpoints (for example SentinelOne Device Control) needs its own allow rule
for each device.
"""
import glob
import os
import re
import shutil
import subprocess
import sys

OSSEC = os.environ.get("WAZUH_HOME", "@OSSEC@")
LIST = OSSEC + "/etc/lists/approved_usb_serials"
GEN = OSSEC + "/etc/rules/9999_0012_usb_approved_generated.xml"
PLACEHOLDER = "PLACEHOLDER-NOT-A-DEVICE"
SERIAL_OK = re.compile(r"^[0-9A-Za-z._-]{4,64}$")


def read_list():
    out = []
    with open(LIST) as f:
        for line in f:
            line = line.rstrip("\n")
            if line.strip():
                k, _, v = line.partition(":")
                out.append((k, v))
    return out


def render(entries):
    serials = [k for k, _ in entries if not k.startswith("PLACEHOLDER-")]
    if not serials:
        return None
    alt = "|".join(re.escape(s) for s in serials)
    return (
        "<!-- GENERATED by usb-approve from etc/lists/approved_usb_serials. Do not edit by hand. -->\n"
        '<group name="windows,usb,">\n\n'
        "  <!-- Security 6416 for a USB storage device whose serial is on the Approved USB list.\n"
        "       Child of 101500. Not in group usb_device_connected, so writes to an approved\n"
        "       device do not trigger the 101507 new-device transfer correlation.\n"
        "       The serial sits inside the device ID, so it is matched with a pattern\n"
        "       built from the list (a CDB list can only match a whole field). -->\n"
        '  <rule id="101516" level="3">\n'
        "    <if_sid>101500</if_sid>\n"
        '    <field name="win.eventdata.deviceId" type="pcre2">(?i)[\\\\]+(' + alt + ")(?![0-9A-Za-z])</field>\n"
        "    <description>APPROVED USB device connected on $(win.system.computer): "
        "$(win.eventdata.deviceDescription) [$(win.eventdata.deviceId)]</description>\n"
        "    <group>usb_device_approved,</group>\n"
        "  </rule>\n\n"
        "  <!-- Partition/Diagnostic 1006 for a USB disk whose serial is on the Approved USB list.\n"
        "       Child of 101501. Not in group usb_device_connected (same reason as 101516). -->\n"
        '  <rule id="101517" level="3">\n'
        "    <if_sid>101501</if_sid>\n"
        '    <list field="win.eventdata.serialNumber" lookup="match_key">etc/lists/approved_usb_serials</list>\n'
        "    <description>APPROVED USB disk attached on $(win.system.computer): $(win.eventdata.manufacturer) "
        "$(win.eventdata.model) SN=$(win.eventdata.serialNumber)</description>\n"
        "    <group>usb_device_approved,</group>\n"
        "  </rule>\n\n"
        "</group>\n")


def put(path, text):
    new = not os.path.exists(path)
    with open(path, "w") as f:
        f.write(text)
    if new:
        try:
            shutil.chown(path, "wazuh", "wazuh")
        except (LookupError, PermissionError):
            pass
        os.chmod(path, 0o660)


def check_ids_free():
    for p in glob.glob(OSSEC + "/etc/rules/*.xml"):
        if p != GEN and re.search(r'id="10151[67]"', open(p, errors="replace").read()):
            sys.exit("STOP: rule ID 101516 or 101517 is already used in %s - nothing changed" % p)


def write_generated(entries):
    xml = render(entries)
    if xml is None:
        if os.path.exists(GEN):
            os.remove(GEN)
    else:
        put(GEN, xml)


def restart_manager():
    if shutil.which("systemctl"):
        subprocess.run(["systemctl", "restart", "wazuh-manager"], check=True)
    else:
        subprocess.run([OSSEC + "/bin/wazuh-control", "restart"], check=True)


def apply(entries):
    check_ids_free()
    old_list = open(LIST).read()
    old_gen = open(GEN).read() if os.path.exists(GEN) else None

    put(LIST, "".join("%s:%s\n" % e for e in entries))
    write_generated(entries)

    r = subprocess.run([OSSEC + "/bin/wazuh-analysisd", "-t"], capture_output=True, text=True)
    bad = [l for l in (r.stdout + r.stderr).splitlines()
           if re.search(r"ERROR|CRITICAL|WARNING.*(10151[67]|approved_usb)", l)]
    if r.returncode != 0 or bad:
        put(LIST, old_list)
        if old_gen is None:
            if os.path.exists(GEN):
                os.remove(GEN)
        else:
            put(GEN, old_gen)
        print("\n".join(bad))
        sys.exit("VALIDATION FAILED - list and rules restored, manager NOT restarted")
    restart_manager()
    print("OK - manager restarted. Approved USB list is now:")
    show(entries)


def show(entries):
    shown = 0
    for k, v in entries:
        if not k.startswith("PLACEHOLDER-"):
            print("  %-28s %s" % (k, v))
            shown += 1
    if not shown:
        print("  (no devices approved yet)")


def main(a):
    if hasattr(os, "geteuid") and os.geteuid() != 0:
        sys.exit("run as root")
    if not os.path.exists(LIST):
        sys.exit("STOP: %s not found - run the installer first" % LIST)
    entries = read_list()
    if a == ["--list"]:
        show(entries)
    elif a == ["--generate"]:
        check_ids_free()
        write_generated(entries)
    elif a == ["--rebuild"]:
        apply(entries)
    elif len(a) == 2 and a[0] == "--remove":
        if a[1] not in [k for k, _ in entries]:
            sys.exit("serial %s is not on the list - nothing changed" % a[1])
        apply([e for e in entries if e[0] != a[1]])
        print("Reminder: also remove this device's allow rule from your endpoint USB control.")
    elif len(a) >= 2 and not a[0].startswith("-"):
        serial, label = a[0], " ".join(a[1:]).strip()
        if not SERIAL_OK.match(serial):
            sys.exit("serial must be 4-64 characters: letters, digits, dot, dash, underscore")
        if not label or ":" in label or "\n" in label:
            sys.exit("label is required and must not contain a colon")
        if serial.lower() in [k.lower() for k, _ in entries]:
            sys.exit("serial %s is already on the list - nothing changed" % serial)
        apply(entries + [(serial, label)])
        print("Reminder: the device also needs an allow rule in your endpoint USB control.")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
