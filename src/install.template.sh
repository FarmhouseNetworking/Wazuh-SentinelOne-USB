# install
# ----------------------------------------------------------------------------
write_ossec_block() {
  cat > "$WORK/ossec-block.xml" <<EOF
<ossec_config>
  <wodle name="command">
    <disabled>no</disabled>
    <tag>sentinelone-pull</tag>
    <command>$PY $POLLER</command>
    <interval>2m</interval>
    <run_on_start>yes</run_on_start>
    <timeout>110</timeout>
    <ignore_output>yes</ignore_output>
  </wodle>
  <localfile>
    <log_format>json</log_format>
    <location>$S1LOG</location>
  </localfile>
</ossec_config>
EOF
}

do_install() {
  [ "${#AGENT_GROUPS[@]}" -gt 0 ] || AGENT_GROUPS=(default)
  preflight
  WORK=$(mktemp -d)
  if [ "$USB_ONLY" -eq 0 ]; then get_credentials; api_test; fi

  if [ "$ASSUME_YES" -eq 0 ] && [ -t 0 ]; then
    local a
    say ""
    if [ "$USB_ONLY" -eq 1 ]; then say "About to install the Windows USB rules, the Approved USB list and usb-approve."
    else say "About to install the SentinelOne collector and rules, the USB rules, the Approved USB list and usb-approve."
    fi
    [ "$NO_AGENT_CONF" -eq 1 ] || say "Windows agent settings will be pushed to agent group(s): ${AGENT_GROUPS[*]}"
    [ "$NO_RESTART" -eq 1 ] || say "wazuh-manager will be restarted."
    read -r -p "Continue? [y/N] " a
    case "$a" in y|Y|yes|YES) ;; *) die "cancelled" ;; esac
  fi

  write_payload_confedit > "$WORK/confedit.py"
  write_payload_agent_security > "$WORK/agent-security.xml"
  write_payload_agent_partition > "$WORK/agent-partition.xml"

  start_backup
  say "Backup: $BK"
  CHANGED=1

  # --- Approved USB list, USB rules, tool ------------------------------------
  track "$OSSEC_CONF"
  track "$LIST"; track "$LIST.cdb"; track "$RULE_USB"; track "$RULE_GEN"; track "$TOOL"
  if [ ! -e "$LIST" ]; then
    printf '%s:placeholder so the list is never empty\n' "$PLACEHOLDER" > "$LIST"
    own wazuh:wazuh 660 "$LIST"
  elif ! grep -q "^$PLACEHOLDER:" "$LIST"; then
    # an existing list is kept; the self-test needs this one line in it
    printf '%s:placeholder so the list is never empty\n' "$PLACEHOLDER" >> "$LIST"
  fi
  write_payload_rule_usb > "$RULE_USB"; own wazuh:wazuh 660 "$RULE_USB"
  mkdir -p "$SBIN"
  write_payload_tool | sed "s|@OSSEC@|$OSSEC|g" > "$TOOL"; own root:root 750 "$TOOL"
  confedit list-add "$OSSEC_CONF" "$LIST_REL" || rollback "could not register the Approved USB list in ossec.conf"
  WAZUH_HOME="$OSSEC" "$PY" "$TOOL" --generate || rollback "could not generate the approved-device rules"

  # --- SentinelOne -----------------------------------------------------------
  if [ "$USB_ONLY" -eq 0 ]; then
    track "$CRED"; track "$POLLER"; track "$RULE_S1"; track "$RULE_DC"; track "$LOGROTATE"; track "$STATE"; track "$S1LOG"
    if [ "$KEEP_CRED" -eq 0 ]; then
      ( umask 077
        cat > "$CRED" <<EOF
[s1]
url = $S1_URL
token = $S1_TOKEN
site_ids = $S1_SITE
# If the API rejects updatedAt__gt on threats, change this to createdAt
threat_ts_field = updatedAt
EOF
      )
      own root:root 600 "$CRED"
    fi
    S1_TOKEN=""
    mkdir -p "$LOGDIR" "$(dirname "$POLLER")"; chmod 750 "$LOGDIR"
    write_payload_poller | sed -e "s|@OSSEC@|$OSSEC|g" -e "s|@LOGDIR@|$LOGDIR|g" > "$POLLER"; own root:wazuh 750 "$POLLER"
    write_payload_rule_s1 > "$RULE_S1"; own wazuh:wazuh 660 "$RULE_S1"
    write_payload_rule_dc > "$RULE_DC"; own wazuh:wazuh 660 "$RULE_DC"
    write_ossec_block
    confedit ossec-block-set "$OSSEC_CONF" "$WORK/ossec-block.xml" || rollback "could not add the collector block to ossec.conf"
    mkdir -p "$LOGROTATE_D"
    cat > "$LOGROTATE" <<EOF
$LOGDIR/*.json {
  daily
  rotate 14
  compress
  delaycompress
  missingok
  notifempty
  copytruncate
}
EOF
  fi

  # --- Windows agent settings, pushed from the manager -----------------------
  local g conf res
  AGENT_NOTES=""
  if [ "$NO_AGENT_CONF" -eq 0 ]; then
    for g in "${AGENT_GROUPS[@]}"; do
      if [ ! -d "$OSSEC/etc/shared/$g" ]; then
        warn "agent group '$g' does not exist ($OSSEC/etc/shared/$g) - skipped"
        AGENT_NOTES="$AGENT_NOTES\n  $g: group not found, skipped"
        continue
      fi
      conf="$OSSEC/etc/shared/$g/agent.conf"
      track "$conf"
      res=$(confedit agent-set "$conf" "$WORK/agent-security.xml" "$WORK/agent-partition.xml") \
        || rollback "could not update $conf"
      own wazuh:wazuh 660 "$conf"
      AGENT_NOTES="$AGENT_NOTES\n  $g: $(printf '%s' "$res" | tr '\n' ' ')"
    done
  fi

  # --- first collection run --------------------------------------------------
  if [ "$USB_ONLY" -eq 0 ]; then
    say "Running the collector once (first run looks back 24 hours)..."
    "$PY" "$POLLER" || true
    if [ -s "$S1LOG" ]; then
      say "Events collected so far, by type:"
      grep -o '"s1_type":"[a-z_]*"' "$S1LOG" | sort | uniq -c | sed 's/^/  /'
      if grep -q '"s1_type":"collector_error"' "$S1LOG"; then
        warn "the collector reported an error:"
        grep '"s1_type":"collector_error"' "$S1LOG" | tail -n 2 | cut -c1-400 >&2
        warn "see docs/TROUBLESHOOTING.md, 'Collector errors'. Installation continues."
      fi
    else
      say "No SentinelOne events in the last 24 hours (fine on a quiet site)."
    fi
  fi

  # --- validate, restart, self-test ------------------------------------------
  say "Validating the configuration..."
  validate || rollback "the new configuration did not validate"
  say "Configuration is valid."

  if [ "$NO_RESTART" -eq 1 ]; then
    say "Not restarting (--no-restart). Run:  systemctl restart wazuh-manager"
    say "then:  $0 selftest"
  else
    restart_manager || rollback "wazuh-manager did not restart"
    RESTARTED=1
    wait_manager || rollback "wazuh-manager is not running after the restart"
    say "wazuh-manager restarted."
    nap 5
    selftest || rollback "the rules did not behave as expected"
  fi

  say ""
  say "Installed (version $VERSION). Backup of the previous state: $BK"
  if [ "$NO_AGENT_CONF" -eq 0 ]; then
    say "Windows agent settings:"
    printf '%b\n' "${AGENT_NOTES#\\n}"
    if printf '%b' "$AGENT_NOTES" | grep -q 'SECURITY=kept-existing'; then
      say "  NOTE: a group already had its own Security channel block, so it was left alone."
      say "  Make sure it does not exclude events 4663 and 4656 (docs/SETUP.md, step 4)."
    fi
  fi
  say ""
  say "Next steps:"
  say "  1. On the Windows endpoints: turn on the audit policy and the HotPlugSecureOpen"
  say "     registry value (windows/ folder; docs/SETUP.md, step 5)."
  say "  2. Approve a device:   usb-approve SERIAL LABEL"
  say "  3. Check any time:     $0 status"
}

