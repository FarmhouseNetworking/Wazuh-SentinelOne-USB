CHANGED=0

say()  { printf '%s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
nap()  { [ -n "${S1USB_NO_SLEEP:-}" ] || sleep "$1"; }

cleanup() { [ -n "$WORK" ] && rm -rf "$WORK"; return 0; }
trap cleanup EXIT

die() {
  printf 'STOP: %s\n' "$*" >&2
  if [ "$CHANGED" -eq 0 ]; then printf 'Nothing was changed.\n' >&2; fi
  exit 1
}

usage() {
  cat <<EOF
wazuh-s1-usb-install.sh $VERSION

