S1_URL=""
S1_SITE=""
S1_TOKEN="${S1_API_TOKEN:-}"
S1_TOKEN_FILE=""
AGENT_GROUPS=()
NO_AGENT_CONF=0
NO_RESTART=0
ASSUME_YES=0
WORK=""
