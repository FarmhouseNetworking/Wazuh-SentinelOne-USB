#!/usr/bin/env bash
# =============================================================================
# wazuh-s1-usb-install.sh
#
# One script to set up, check and remove on a self-hosted Wazuh manager:
#   - SentinelOne threats and console activity, pulled from the SentinelOne API
#     (outbound HTTPS only), with rules 100600-100620
#   - USB removable-media rules for Windows endpoints (101500-101508)
#   - SentinelOne Device Control rules (101510-101515)
#   - an Approved USB list and the usb-approve tool (generated rules 101516, 101517)
#   - the Windows agent settings those rules need, pushed from the manager
#
# Usage:  sudo ./wazuh-s1-usb-install.sh install|status|selftest|uninstall [options]
#         ./wazuh-s1-usb-install.sh help
#
# https://github.com/FarmhouseNetworking/Wazuh-SentinelOne-USB      MIT License
#
# GENERATED FILE - edit src/install.template.sh and payload/, then run
# tools/build.py. Do not edit this file by hand.
# =============================================================================
set -euo pipefail
